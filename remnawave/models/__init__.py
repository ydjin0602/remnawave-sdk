# ---- Enable populate_by_name on all models (construct by snake_case or alias) ----
def _enable_populate_by_name() -> None:
    from pydantic import BaseModel

    seen: set[type] = set()
    stack = [BaseModel]
    while stack:
        cls = stack.pop()
        for sub in cls.__subclasses__():
            if sub in seen:
                continue
            seen.add(sub)
            stack.append(sub)
            try:
                cfg = sub.model_config
                cfg["populate_by_name"] = True
                sub.model_rebuild(force=True)
            except Exception:  # noqa: BLE001, S110 - best-effort config tweak
                pass


_enable_populate_by_name()
